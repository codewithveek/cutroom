import path from "node:path";
import { productBrand } from "@cutroom/config";
import type { ClaimResult } from "@cutroom/scene-spec";
import { lookTokensById } from "@cutroom/video-kit";
import type { RunRecord } from "./run-schema";

const modeBadge: Readonly<Record<RunRecord["request"]["privacyMode"], string>> = {
  local: "Ran fully local: the code never left this machine.",
  hybrid: "Rendered in the cloud; the code stayed local. Only the approved storyboard bundle was uploaded.",
  cloud: "Ran in the cloud.",
};

function list(items: ReadonlyArray<string>, empty: string): string {
  return items.length > 0 ? items.map((item) => `- ${item}`).join("\n") : `- ${empty}`;
}

function illustrativeItems(run: RunRecord, claimResults: ReadonlyArray<ClaimResult>): string[] {
  const items: string[] = [];
  if (run.request.music.kind === "generated") {
    items.push(
      `Music: a placeholder "${run.request.music.bed}" bed generated in code (no third-party licence). Replace it for a public launch if you like.`,
    );
  }
  if (run.request.music.kind === "uploaded") {
    items.push(
      `Music: your upload${run.request.music.fileName ? ` "${run.request.music.fileName}"` : ""}. Make sure you hold the rights to publish it.`,
    );
  }
  for (const result of claimResults.filter((claim) => claim.verdict === "weak")) {
    items.push(
      `"${result.claimText}" was judged weak${result.suggestion ? `; suggested: ${result.suggestion}` : ""}.`,
    );
  }
  items.push(
    "Any names, amounts or hostnames in terminal and code scenes are the repository's own placeholder data.",
  );
  return items;
}

function licences(run: RunRecord): string[] {
  const items = [
    "Remotion: free for individuals and companies of up to 3 people; larger companies need a company licence.",
  ];
  if (run.providers.voiceProvider === "kokoro")
    items.push("Voice: Kokoro-82M, Apache-2.0 (AI-generated voice).");
  if (run.providers.voiceProvider === "elevenlabs")
    items.push("Voice: ElevenLabs, commercial use on paid plans (AI-generated voice).");
  if (run.request.music.kind === "generated")
    items.push("Music and sound effects: generated by Cutroom, no third-party rights.");
  if (run.request.music.kind === "uploaded")
    items.push("Music: supplied by you (your licence); sound effects generated by Cutroom.");
  items.push("Fonts: Inter, Plus Jakarta Sans, Inter Tight, Geist (SIL Open Font License).");
  return items;
}

/** The delivery note (FR-RD-7): what was made, with what, and what still needs a human. */
export function buildDeliveryNote(run: RunRecord): string {
  const version = run.storyboardVersions.find((candidate) => candidate.id === run.approval?.versionId);
  const claimResults = version?.claimResults ?? [];
  const look = run.look ? lookTokensById[run.look].label : "unknown";
  const files = run.assets
    .filter((asset) => asset.kind !== "delivery-note" && asset.kind !== "still")
    .map((asset) => {
      const duration = asset.durationMs ? ` · ${(asset.durationMs / 1000).toFixed(1)} s` : "";
      return `\`${path.basename(asset.filePath)}\` (${asset.kind}${asset.ratio ? ` ${asset.ratio}` : ""}${duration})`;
    });
  const overrides = claimResults.filter((result) => result.overrideReason);
  const providers = run.providers;
  return [
    `# Delivery note · ${version?.storyboard.title ?? run.id}`,
    "",
    `> ${modeBadge[run.request.privacyMode]}`,
    "",
    "## Files",
    list(files, "No files were produced."),
    "",
    "## How it was made",
    `- Video type: ${run.request.videoType} · look: ${look}${run.lookReason ? ` (${run.lookReason})` : ""}`,
    `- Model: ${providers?.modelId ?? "unknown"} via ${providers?.modelProvider ?? "unknown"}`,
    `- Voice: ${providers?.voiceProvider ?? "none"}${providers?.isAiVoice ? " (AI-generated voice)" : ""}`,
    `- Claims audited: ${claimResults.length} (${claimResults.filter((result) => result.verdict === "supported").length} supported, ${claimResults.filter((result) => result.verdict === "weak").length} weak, ${claimResults.filter((result) => result.verdict === "unsupported").length} unsupported)`,
    "",
    "## What is illustrative",
    list(illustrativeItems(run, claimResults), "Nothing."),
    "",
    "## Claim overrides",
    list(
      overrides.map((result) => `"${result.claimText}": ${result.overrideReason}`),
      "None. Every claim shown was supported or weak.",
    ),
    "",
    "## Licences",
    list(licences(run), "None."),
    "",
    `Quality stills (scene ends and transition midpoints) are in \`quality/\`: ${run.assets.filter((asset) => asset.kind === "still").length} frames.`,
    "",
    "## Judge by eye and ear before you post",
    list(
      [
        "Pronunciation of the product name and any acronyms (respell them in `say` if needed).",
        "Music level under the voice on your speakers and on a phone.",
        "That the first frame (the thumbnail) reads at feed size.",
        "Captions line up with the voice in the vertical cut.",
      ],
      "",
    ),
    "",
    `_Made with ${productBrand.name}. ${productBrand.creditLine}_`,
    "",
  ].join("\n");
}
