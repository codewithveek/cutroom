import path from "node:path";
import { drizzle, type NodePgDatabase } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import { Pool } from "pg";
import * as schema from "./schema";

export type CutroomDatabase = NodePgDatabase<typeof schema>;

export interface DatabaseHandle {
  db: CutroomDatabase;
  pool: Pool;
  close: () => Promise<void>;
}

export function createDatabase(options: {
  connectionString: string;
  maxConnections?: number;
}): DatabaseHandle {
  const pool = new Pool({ connectionString: options.connectionString, max: options.maxConnections ?? 10 });
  return { db: drizzle(pool, { schema }), pool, close: () => pool.end() };
}

/** Migrations generated by drizzle-kit live next to the package's sources. */
export const migrationsFolder = path.resolve(import.meta.dirname, "..", "drizzle");

export async function runMigrations(db: CutroomDatabase): Promise<void> {
  await migrate(db, { migrationsFolder });
}
